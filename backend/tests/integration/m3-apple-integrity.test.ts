    for (const mutation of [/^\/purchases .*POST/, /^\/subscriptions\/(purchase|change-plan|cancel|resume)/]) {
      assert.ok(!routes.some((r) => mutation.test(r)), `unexpected mock mutation route ${mutation}`);
    }

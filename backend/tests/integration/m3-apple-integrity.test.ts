  it('[BR][SUB-02..06] full plan ladder via the app path: Basic→Premium→Ultra (immediate), Ultra→Premium→Basic (at renewal), cancel, expire, restore', async () => {
    const T = Date.now();
    nowMs = T;
    const app = appWithClock();
    try {
      const u = await user(app);
      const send = async (signedTransaction: string, signedRenewalInfo?: string) => {
        const r = await app.inject({ method: 'POST', url: '/billing/apple/transactions', headers: { authorization: `Bearer ${u.token}` }, payload: { signedTransaction, ...(signedRenewalInfo && { signedRenewalInfo }) } });
        return { status: r.statusCode, body: r.json() as { result: string; renewalInfoResult: string | null } };
      };
      const view = async () => (await app.inject({ method: 'GET', url: '/subscriptions/current', headers: { authorization: `Bearer ${u.token}` } })).json().subscription;
      const subLedger = async () => (await db.pool.query<{ entry_type: string; delta: number; expiration_reason: string | null }>(
        `SELECT entry_type, delta, expiration_reason FROM credit_ledger WHERE user_id = $1 AND bucket = 'SUBSCRIPTION' ORDER BY id`, [u.userId])).rows;
      const H = 3600_000;
      const O = newTransactionId();
      const tx = (productId: string, start: number, end: number) => signer.transaction({ productId, originalTransactionId: O, purchaseDate: start, expiresDate: end, appAccountToken: u.appAccountToken });
      const intent = (autoRenewProductId: string, autoRenewStatus = 1) => signer.renewalInfo({ originalTransactionId: O, productId: PRODUCT.ULTRA, autoRenewProductId, autoRenewStatus, signedDate: nowMs });

      assert.equal((await send(signer.transaction({ productId: PRODUCT.S, appAccountToken: u.appAccountToken }))).status, 201);
      const basic = signer.transaction({ productId: PRODUCT.BASIC, transactionId: O, purchaseDate: T - H, expiresDate: T - H + 7 * DAY, appAccountToken: u.appAccountToken });
      assert.equal((await send(basic)).body.result, 'SUBSCRIPTION_STARTED');
      assert.deepEqual(await balances(u.userId), { SUBSCRIPTION: 3000, CONSUMABLE: 5000, REWARD: 0, PROMOTIONAL: 0 });

      // Basic → Premium: Apple applies upgrades immediately (new transaction inside the current period).
      nowMs = T + H;
      assert.equal((await send(tx(PRODUCT.PREMIUM, nowMs, nowMs + 7 * DAY))).body.result, 'UPGRADED');
      assert.equal((await balances(u.userId)).SUBSCRIPTION, 6000, 'Basic remainder expired, full Premium allotment');
      // Premium → Ultra: immediate.
      nowMs = T + 2 * H;
      const ultra = tx(PRODUCT.ULTRA, nowMs, nowMs + 7 * DAY);
      assert.equal((await send(ultra)).body.result, 'UPGRADED');
      assert.equal((await balances(u.userId)).SUBSCRIPTION, 12000);
      assert.equal((await view()).planId, 'ULTRA_WEEKLY');

      // Ultra → Premium requested: only the renewal intent changes; plan and credits stay until renewal (SUB-04).
      nowMs = T + 3 * H;
      const req1 = await send(ultra, intent(PRODUCT.PREMIUM));
      assert.equal(req1.body.result, 'IGNORED_DUPLICATE_TRANSACTION');
      assert.equal(req1.body.renewalInfoResult, 'DOWNGRADE_SCHEDULED');
      assert.equal((await balances(u.userId)).SUBSCRIPTION, 12000);
      assert.deepEqual([(await view()).planId, (await view()).pendingPlanId], ['ULTRA_WEEKLY', 'PREMIUM_WEEKLY']);
      // Apple delivers the renewal before it starts (F-M3-04): scheduled (202), never granted ahead of time.
      const ultraEnd = T + 2 * H + 7 * DAY;
      const premiumRenewal = tx(PRODUCT.PREMIUM, ultraEnd, ultraEnd + 7 * DAY);
      nowMs = ultraEnd - 60_000;
      const early = await send(premiumRenewal);
      assert.deepEqual([early.status, early.body.result], [202, 'RENEWAL_SCHEDULED']);
      assert.equal((await balances(u.userId)).SUBSCRIPTION, 12000);
      // Effective at renewal (SUB-05), with no further delivery: the first read after the start applies it.
      nowMs = ultraEnd + 1000;
      await app.inject({ method: 'GET', url: '/wallet', headers: { authorization: `Bearer ${u.token}` } });
      assert.equal((await balances(u.userId)).SUBSCRIPTION, 6000);
      assert.equal((await send(premiumRenewal)).body.result, 'IGNORED_DUPLICATE_TRANSACTION');
      assert.deepEqual([(await view()).planId, (await view()).pendingPlanId], ['PREMIUM_WEEKLY', null]);

      // Premium → Basic requested, then effective at the next renewal.
      nowMs += H;
      assert.equal((await send(premiumRenewal, intent(PRODUCT.BASIC))).body.renewalInfoResult, 'DOWNGRADE_SCHEDULED');
      assert.equal((await balances(u.userId)).SUBSCRIPTION, 6000);
      const premiumEnd = ultraEnd + 7 * DAY;
      const basicRenewal = tx(PRODUCT.BASIC, premiumEnd, premiumEnd + 7 * DAY);
      nowMs = premiumEnd + 1000;
      assert.equal((await send(basicRenewal)).body.result, 'RENEWED_DOWNGRADED');
      assert.equal((await balances(u.userId)).SUBSCRIPTION, 3000);

      // Cancellation: auto-renew off only; entitlement and credits kept to the period end (PRD §2.1).
      nowMs += H;
      assert.equal((await send(basicRenewal, intent(PRODUCT.BASIC, 0))).body.renewalInfoResult, 'AUTO_RENEW_DISABLED');
      assert.deepEqual([(await view()).entitled, (await view()).autoRenew, (await balances(u.userId)).SUBSCRIPTION], [true, false, 3000]);

      // Expiration: after the verified end the remainder expires on the next read; nothing renews.
      nowMs = premiumEnd + 7 * DAY + 1000;
      assert.deepEqual([(await view()).entitled, (await balances(u.userId)).SUBSCRIPTION], [false, 0]);

      // Restore (same account, same Apple ID): every transaction is a duplicate; nothing changes.
      const before = await footprint(u.userId);
      for (const jws of [basic, ultra, premiumRenewal, basicRenewal]) assert.equal((await send(jws)).body.result, 'IGNORED_DUPLICATE_TRANSACTION');
      assert.deepEqual(await footprint(u.userId), before);

      assert.deepEqual(await subLedger(), [
        { entry_type: 'SUBSCRIPTION_GRANT', delta: 3000, expiration_reason: null },
        { entry_type: 'SUBSCRIPTION_EXPIRATION', delta: -3000, expiration_reason: 'SUPERSEDED' },
        { entry_type: 'SUBSCRIPTION_GRANT', delta: 6000, expiration_reason: null },
        { entry_type: 'SUBSCRIPTION_EXPIRATION', delta: -6000, expiration_reason: 'SUPERSEDED' },
        { entry_type: 'SUBSCRIPTION_GRANT', delta: 12000, expiration_reason: null },
        // At a renewal the previous period already ended: its remainder expires PERIOD_ENDED (D-029) before the grant.
        { entry_type: 'SUBSCRIPTION_EXPIRATION', delta: -12000, expiration_reason: 'PERIOD_ENDED' },
        { entry_type: 'SUBSCRIPTION_GRANT', delta: 6000, expiration_reason: null },
        { entry_type: 'SUBSCRIPTION_EXPIRATION', delta: -6000, expiration_reason: 'PERIOD_ENDED' },
        { entry_type: 'SUBSCRIPTION_GRANT', delta: 3000, expiration_reason: null },
        { entry_type: 'SUBSCRIPTION_EXPIRATION', delta: -3000, expiration_reason: 'PERIOD_ENDED' },
      ]);
      assert.equal((await balances(u.userId)).CONSUMABLE, 5000, 'consumables never change with plan changes');
      await assertLedgerReconciles(u.userId);
    } finally {
      await app.close();
    }
  });

